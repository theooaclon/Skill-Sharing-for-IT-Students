    private void addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addActionPerformed
        String skill = JOptionPane.showInputDialog(this, "Enter your skills:");
    
        if (skill == null || skill.trim().isEmpty()) {
            return;
        }
        skill = skill.trim();

        try (Connection conn = DBConnection.getConnection()) {
            int skillId = getOrCreateSkillId(conn, skill);

            String insertSql = "INSERT IGNORE INTO UserSkill (StudentID, SkillID) VALUES (?, ?)";
            try (PreparedStatement stmt = conn.prepareStatement(insertSql)) {
                stmt.setString(1, loggedinuser.getStudentId());
                stmt.setInt(2, skillId);
                stmt.executeUpdate();
            }

            loadSkills();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error adding skill: " + e.getMessage());
        }
    }//GEN-LAST:event_addActionPerformed

    private void add1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_add1ActionPerformed
        String skill = JOptionPane.showInputDialog(this, "Enter the skill to remove:");
        
        if (skill == null || skill.trim().isEmpty()) {
            return;
        }
        skill = skill.trim();
        
        String sql = "DELETE us FROM UserSkill us " +
                     "JOIN Skills sk ON us.SkillID = sk.SkillID " +
                     "WHERE us.StudentID = ? AND sk.SkillName = ?";
        
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {
            
            stmt.setString(1, loggedinuser.getStudentId());
            stmt.setString(2, skill);
            int rows = stmt.executeUpdate();
            
            if (rows > 0) {
                loadSkills();
                JOptionPane.showMessageDialog(this, "Skill removed!");
            } else {
                JOptionPane.showMessageDialog(this, "Skill not found");
            }
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error removing skill: " + e.getMessage());
        }
    }//GEN-LAST:event_add1ActionPerformed

