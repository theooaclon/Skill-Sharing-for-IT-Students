    private void loadSkills() {
        show.setText("");
        
        String sql = "SELECT sk.SkillName FROM UserSkill us " +"JOIN Skills sk ON us.SkillID = sk.SkillID " +"WHERE us.StudentID = ?";
        
        try (Connection conn = DBConnection.getConnection();
            PreparedStatement stmt = conn.prepareStatement(sql)) {
            stmt.setString(1, loggedinuser.getStudentId());
            ResultSet rs = stmt.executeQuery();
            while (rs.next()) {
                show.append("- " + rs.getString("SkillName") + "\n");
            }
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading skills: " + e.getMessage());
        }
    }
    private int getOrCreateSkillId(Connection conn, String skillName) throws SQLException {
        String findSql = "SELECT SkillID FROM Skills WHERE SkillName = ?";
        try (PreparedStatement findStmt = conn.prepareStatement(findSql)) {
            findStmt.setString(1, skillName);
            ResultSet rs = findStmt.executeQuery();
            if (rs.next()) {
                return rs.getInt("SkillID");
            }
        }
        String insertSql = "INSERT INTO Skills (SkillName) VALUES (?)";
        try (PreparedStatement insertStmt = conn.prepareStatement(insertSql, java.sql.Statement.RETURN_GENERATED_KEYS)) {
            insertStmt.setString(1, skillName);
            insertStmt.executeUpdate();
            ResultSet keys = insertStmt.getGeneratedKeys();
            if (keys.next()) {
                return keys.getInt(1);
            }
        }
        
        throw new SQLException("Could not create skill");
    }
    

