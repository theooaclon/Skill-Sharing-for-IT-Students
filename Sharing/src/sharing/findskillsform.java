    private void reqActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_reqActionPerformed
        int selectedRow = showskills.getSelectedRow();
        
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a student first");
            return;
        }
        
        String helperId = showskills.getValueAt(selectedRow, 2).toString();
        String skillName = showskills.getValueAt(selectedRow, 1).toString();
        
        String getSkillIdSql = "SELECT SkillID FROM Skills WHERE SkillName = ?";
        String insertSql = "INSERT INTO Request (RequesterID, HelperID, SkillID, Status, DateRequested) " +"VALUES (?, ?, ?, 'Pending', CURDATE())";
        
        try (Connection conn = DBConnection.getConnection()) {
            
            int skillId;
            try (PreparedStatement skillStmt = conn.prepareStatement(getSkillIdSql)) {
                skillStmt.setString(1, skillName);
                ResultSet rs = skillStmt.executeQuery();
                if (!rs.next()) {
                    JOptionPane.showMessageDialog(this, "Skill not found.");
                    return;
                }
                skillId = rs.getInt("SkillID");
            }
            
            try (PreparedStatement insertStmt = conn.prepareStatement(insertSql)) {
                insertStmt.setString(1, loggedinuser.getStudentId());
                insertStmt.setString(2, helperId);
                insertStmt.setInt(3, skillId);
                insertStmt.executeUpdate();
            }
            
            JOptionPane.showMessageDialog(this, "Request sent!");
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error sending request: " + e.getMessage());
        }
    }//GEN-LAST:event_reqActionPerformed

