    private void populateSkillCombo() {
        skillCombo.removeAllItems();
        skillCombo.addItem("Select Skills");
        skillCombo.addItem("All Skills");
        
        String sql = "SELECT DISTINCT SkillName FROM Skills ORDER BY SkillName";
        
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {
            
            ResultSet rs = stmt.executeQuery();
            while (rs.next()) {
                skillCombo.addItem(rs.getString("SkillName"));
            }
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading skills: " + e.getMessage());
        }
    }

    private void skillComboActionPerformed(java.awt.event.ActionEvent evt) {
        String selected = (String) skillCombo.getSelectedItem();
        
        if (selected == null || selected.equals("Select Skills")) {
            return; 
        }
        if (selected.equals("All Skills")) {
            displayStudents(null);
        } else {
            displayStudents(new String[]{ selected });
        }
    }
    
    private void searchSkills () {
        String searches = search.getText().trim();
    
        if (searches.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter a skill");
            return;
        }
    
        String[] skillsToSearch = searches.split(",");
        boolean found = displayStudents(skillsToSearch);
    
        if (!found) {
            JOptionPane.showMessageDialog(this, "No students found with those skills");
        }
    }

    private boolean displayStudents(String[] skillsFilter) {
        DefaultTableModel model = (DefaultTableModel) showskills.getModel();
        model.setRowCount(0);
        boolean found = false;

        StringBuilder sql = new StringBuilder(
            "SELECT s.Name, sk.SkillName, s.StudentID, s.SchoolYear " +
            "FROM Student s " +
            "JOIN UserSkill us ON s.StudentID = us.StudentID " +
            "JOIN Skills sk ON us.SkillID = sk.SkillID " +
            "WHERE s.StudentID != ?"
        );

        if (skillsFilter != null) {
            sql.append(" AND (");
            for (int i = 0; i < skillsFilter.length; i++) {
                if (i > 0) sql.append(" OR ");
                sql.append("sk.SkillName = ?");
            }
            sql.append(")");
        }

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql.toString())) {

            stmt.setString(1, loggedinuser.getStudentId());

            if (skillsFilter != null) {
                for (int i = 0; i < skillsFilter.length; i++) {
                    stmt.setString(i + 2, skillsFilter[i].trim());
                }
            }

            ResultSet rs = stmt.executeQuery();
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("Name"),
                    rs.getString("SkillName"),
                    rs.getString("StudentID"),
                    rs.getString("SchoolYear")
                });
                found = true;
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error searching skills: " + e.getMessage());
        }

        return found;
    }

