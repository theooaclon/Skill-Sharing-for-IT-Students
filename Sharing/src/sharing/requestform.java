    private void updateRequestStatus(int requestId, String expectedCurrentStatus, String newStatus) {
        String checkSql = "SELECT Status FROM Request WHERE RequestID = ?";
        String updateSql = "UPDATE Request SET Status = ? WHERE RequestID = ?";

        try (Connection conn = DBConnection.getConnection()) {

            try (PreparedStatement checkStmt = conn.prepareStatement(checkSql)) {
                checkStmt.setInt(1, requestId);
                ResultSet rs = checkStmt.executeQuery();
                if (rs.next() && !rs.getString("Status").equalsIgnoreCase(expectedCurrentStatus)) {
                    JOptionPane.showMessageDialog(this, "this request has already been " + rs.getString("Status"));
                    return;
                }
            }

            try (PreparedStatement updateStmt = conn.prepareStatement(updateSql)) {
                updateStmt.setString(1, newStatus);
                updateStmt.setInt(2, requestId);
                updateStmt.executeUpdate();
            }

            JOptionPane.showMessageDialog(this, "request " + newStatus.toLowerCase() + "!");
            loadRequest();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error updating request: " + e.getMessage());
        }
    }
    private void notesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_notesActionPerformed
        int row = rq.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a request first");
            return;
        }

        int requestId = displayedRequestIds.get(row);
        String requesterName = rq.getValueAt(row, 0).toString();
        String status = rq.getValueAt(row, 2).toString();

        if (!status.equalsIgnoreCase("Accepted")) {
            JOptionPane.showMessageDialog(this, "Notes are only available for accepted requests");
            return;
        }

        String getSql = "SELECT Notes, MeetupDate, MeetupTime FROM Request WHERE RequestID = ?";
        String currentNotes = "", currentDate = "", currentTime = "";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement getStmt = conn.prepareStatement(getSql)) {

            getStmt.setInt(1, requestId);
            ResultSet rs = getStmt.executeQuery();
            if (rs.next()) {
                currentNotes = rs.getString("Notes") != null ? rs.getString("Notes") : "";
                currentDate = rs.getString("MeetupDate") != null ? rs.getString("MeetupDate") : "";
                currentTime = rs.getString("MeetupTime") != null ? rs.getString("MeetupTime") : "";
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading notes: " + e.getMessage());
            return;
        }

        String inputNotes = JOptionPane.showInputDialog(this, "Write meetup notes for " + requesterName + ":", currentNotes);
        if (inputNotes == null) return;

        String inputDate = JOptionPane.showInputDialog(this, "Meetup date (e.g. 10/15/2026):", currentDate);
        if (inputDate == null) return;

        String inputTime = JOptionPane.showInputDialog(this, "Meetup time (e.g. 3:00 PM):", currentTime);
        if (inputTime == null) return;

        String updateSql = "UPDATE Request SET Notes = ?, MeetupDate = ?, MeetupTime = ? WHERE RequestID = ?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement updateStmt = conn.prepareStatement(updateSql)) {

            updateStmt.setString(1, inputNotes.trim());
            updateStmt.setString(2, inputDate.trim());
            updateStmt.setString(3, inputTime.trim());
            updateStmt.setInt(4, requestId);
            updateStmt.executeUpdate();

            JOptionPane.showMessageDialog(this, "Notes sent!");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error saving notes: " + e.getMessage());
        }
    }//GEN-LAST:event_notesActionPerformed

