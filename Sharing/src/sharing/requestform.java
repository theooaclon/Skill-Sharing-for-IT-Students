    private void loadRequest() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) rq.getModel();
        model.setRowCount(0);
        displayedRequestIds.clear();
        
        String sql = "SELECT r.RequestID, s.Name, sk.SkillName, r.Status " +
                     "FROM Request r " +
                     "JOIN Student s ON r.RequesterID = s.StudentID " +
                     "JOIN Skills sk ON r.SkillID = sk.SkillID " +
                     "WHERE r.HelperID = ?";
        
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {
            
            stmt.setString(1, loggedinuser.getStudentId());
            ResultSet rs = stmt.executeQuery();
            
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("Name"),
                    rs.getString("SkillName"),
                    rs.getString("Status")
                });
                displayedRequestIds.add(rs.getInt("RequestID"));
            }
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading requests: " + e.getMessage());
        }
    }


