    private void cretActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cretActionPerformed
           String studentid = cretid.getText();
           String name = cretname.getText();
           String username = cretusername.getText();
           
           String password = cretpass.getText();
           String confirms = confirm.getText();
           String schoolYear = (String) cretyear.getSelectedItem();
           
           String result = register.registeruser(studentid, name, username, password, confirms, schoolYear);
           
           if(result.equals("registered sucessfully!")) {
               JOptionPane.showMessageDialog(null, "registeration sucessful!");
               
               JFrame frame = new JFrame("Register");

            loginform login = new loginform();

            frame.add(login);
            frame.setSize(1000, 800);
            frame.setLocationRelativeTo(null);
            frame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
            frame.setVisible(true);

            this.setVisible(false);
               
           } else {
               JOptionPane.showMessageDialog(null, result);
           }
           
           
           
           
    }//GEN-LAST:event_cretActionPerformed

