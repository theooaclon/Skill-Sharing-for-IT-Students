    private void viewNotesBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewNotesBtnActionPerformed
        int row = rq.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a request first.");
            return;
        }

        int requestId = displayedRequestIds.get(row);
            String helperName = rq.getValueAt(row, 0).toString();
            String status = rq.getValueAt(row, 2).toString();

            if (!status.equalsIgnoreCase("Accepted")) {
                JOptionPane.showMessageDialog(this, "Notes are only available once a request is accepted.");
                return;
        }

            String sql = "SELECT Notes, MeetupDate, MeetupTime FROM Request WHERE RequestID = ?";

            try (Connection conn = DBConnection.getConnection();
            PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setInt(1, requestId);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                String notes = rs.getString("Notes");
                if (notes == null || notes.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "No notes yet from " + helperName + ".");
                } else {
                    JOptionPane.showMessageDialog(this,
                        "Meetup notes from " + helperName + ":\n\n" +
                        notes + "\n\n" +
                        "Date: " + rs.getString("MeetupDate") + "\n" +
                        "Time: " + rs.getString("MeetupTime")
                    );
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading notes: " + e.getMessage());
        }
    }//GEN-LAST:event_viewNotesBtnActionPerformed

